//! `.html` / `.htm`: `BeautifulSoup(text, "html.parser").get_text("\n")`.
//!
//! A port of CPython 3.13.15 `html.parser.HTMLParser` (`convert_charrefs=False`, as bs4 uses it) plus the parts of bs4 4.15.0 that
//! decide what `get_text` returns: `BeautifulSoupHTMLParser` (`bs4/builder/_htmlparser.py`) and the tree builder
//! (`BeautifulSoup.handle_starttag / _popToTag / endData`). The Python regular expressions are hand-written scanners that follow
//! the regex's backtracking exactly; the Python function names are kept so the port can be read side by side.
//!
//! Known gaps (documented, never hit by sane input): `int()` of a character-reference "name" that holds non-ASCII Unicode
//! decimal digits (Python converts them, this port does not), and a numeric reference of more than 4300 decimal digits (Python
//! raises `ValueError` out of `BeautifulSoup()`, this function cannot fail and gives U+FFFD).

use std::collections::HashMap;
use std::sync::OnceLock;

use versevision_core::pystr;

/// Generated by `python/scripts/gen_html_entities.py` (entity table of bs4 and its Windows-1252 table).
const DATA: &str = include_str!("html_data.txt");

struct Tables {
    /// bs4 `EntitySubstitution.HTML_ENTITY_TO_CHARACTER`.
    entities: HashMap<&'static str, String>,
    /// bs4 `UnicodeDammit.WINDOWS_1252_TO_UTF8` for 0x80..=0x9f.
    windows_1252: HashMap<u32, char>,
}

fn tables() -> &'static Tables {
    static TABLES: OnceLock<Tables> = OnceLock::new();
    TABLES.get_or_init(|| {
        let mut entities = HashMap::new();
        let mut windows_1252 = HashMap::new();
        let chars = |hex: &str| -> String {
            hex.split(',')
                .filter_map(|h| u32::from_str_radix(h, 16).ok())
                .filter_map(char::from_u32)
                .collect()
        };
        for line in DATA.lines() {
            let mut parts = line.split(' ');
            let (Some(kind), Some(a), Some(b)) = (parts.next(), parts.next(), parts.next()) else {
                continue;
            };
            match kind {
                "E" => {
                    entities.insert(a, chars(b));
                }
                "W" => {
                    if let (Ok(n), Some(c)) = (u32::from_str_radix(a, 16), chars(b).chars().next())
                    {
                        windows_1252.insert(n, c);
                    }
                }
                _ => {}
            }
        }
        Tables {
            entities,
            windows_1252,
        }
    })
}

// ---------------------------------------------------------------------------------------------------------------------
// bs4 tree builder (only what get_text can observe)
// ---------------------------------------------------------------------------------------------------------------------

/// `HTMLTreeBuilder.DEFAULT_EMPTY_ELEMENT_TAGS`
const EMPTY_ELEMENT_TAGS: &[&str] = &[
    "area", "base", "br", "col", "embed", "hr", "img", "input", "keygen", "link", "menuitem",
    "meta", "param", "source", "track", "wbr", "basefont", "bgsound", "command", "frame", "image",
    "isindex", "nextid", "spacer",
];
/// `HTMLTreeBuilder.DEFAULT_STRING_CONTAINERS`: their strings are RubyText/Stylesheet/Script/TemplateString, not part of the root's get_text.
const STRING_CONTAINERS: &[&str] = &["rt", "rp", "style", "script", "template"];
/// `HTMLTreeBuilder.DEFAULT_PRESERVE_WHITESPACE_TAGS`
const PRESERVE_WHITESPACE_TAGS: &[&str] = &["pre", "textarea"];

/// The class `endData(containerClass)` makes. The root's `interesting_string_types` is exactly {NavigableString, CData}.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Kind {
    Text,
    CData,
}

#[derive(Default)]
struct Soup {
    current_data: Vec<String>,
    tag_stack: Vec<String>,
    open_tag_counter: HashMap<String, i64>,
    preserve_whitespace_tag_stack: usize,
    string_container_stack: usize,
    strings: Vec<String>,
}

/// bs4 `ASCII_SPACES`
fn is_ascii_space(c: char) -> bool {
    matches!(c, ' ' | '\n' | '\t' | '\x0c' | '\r')
}

impl Soup {
    fn pop_tag(&mut self) {
        let Some(name) = self.tag_stack.pop() else {
            return;
        };
        if let Some(count) = self.open_tag_counter.get_mut(&name) {
            *count -= 1;
        }
        if PRESERVE_WHITESPACE_TAGS.contains(&name.as_str())
            && self.preserve_whitespace_tag_stack > 0
        {
            self.preserve_whitespace_tag_stack -= 1;
        }
        if STRING_CONTAINERS.contains(&name.as_str()) && self.string_container_stack > 0 {
            self.string_container_stack -= 1;
        }
    }

    fn push_tag(&mut self, name: &str) {
        self.tag_stack.push(name.to_string());
        *self.open_tag_counter.entry(name.to_string()).or_insert(0) += 1;
        if PRESERVE_WHITESPACE_TAGS.contains(&name) {
            self.preserve_whitespace_tag_stack += 1;
        }
        if STRING_CONTAINERS.contains(&name) {
            self.string_container_stack += 1;
        }
    }

    /// `BeautifulSoup.endData`: note that an empty string collapses to `" "` (it is "all whitespace").
    fn end_data(&mut self, kind: Kind) {
        if self.current_data.is_empty() {
            return;
        }
        let mut current = self.current_data.concat();
        self.current_data.clear();
        if self.preserve_whitespace_tag_stack == 0 && current.chars().all(is_ascii_space) {
            current = if current.contains('\n') {
                "\n".into()
            } else {
                " ".into()
            };
        }
        let in_text = match kind {
            Kind::Text => self.string_container_stack == 0,
            Kind::CData => true,
        };
        if in_text {
            self.strings.push(current);
        }
    }

    /// `BeautifulSoup._popToTag`
    fn pop_to_tag(&mut self, name: &str) {
        if name == "[document]" {
            return;
        }
        for i in (1..self.tag_stack.len()).rev() {
            if self.open_tag_counter.get(name).copied().unwrap_or(0) == 0 {
                break;
            }
            let found = self.tag_stack[i] == name;
            self.pop_tag();
            if found {
                break;
            }
        }
    }

    fn handle_starttag(&mut self, name: &str) {
        self.end_data(Kind::Text);
        self.push_tag(name);
    }

    fn handle_endtag(&mut self, name: &str) {
        self.end_data(Kind::Text);
        self.pop_to_tag(name);
    }

    fn handle_data(&mut self, data: &str) {
        self.current_data.push(data.to_string());
    }

    /// `handle_comment` / `handle_decl` / `handle_pi`: flush, then a string of a class that is not in the text (its content is irrelevant).
    fn handle_non_text(&mut self) {
        self.end_data(Kind::Text);
    }
}

