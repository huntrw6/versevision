/// Python `int(text, base)` for base 10 / 16 (saturating far above U+10FFFF); `None` is `ValueError`.
fn py_int(text: &str, base: u32) -> Option<i128> {
    let text = pystr::strip(text);
    let (negative, mut rest) = match text.as_bytes().first() {
        Some(b'-') => (true, &text[1..]),
        Some(b'+') => (false, &text[1..]),
        _ => (false, text),
    };
    if base == 16 && (rest.starts_with("0x") || rest.starts_with("0X")) {
        rest = &rest[2..];
        rest = rest.strip_prefix('_').unwrap_or(rest);
    }
    if rest.is_empty() {
        return None;
    }
    let mut value: i128 = 0;
    let mut previous_underscore = true; // a leading underscore is invalid
    for c in rest.chars() {
        if c == '_' {
            if previous_underscore {
                return None;
            }
            previous_underscore = true;
            continue;
        }
        let digit = c.to_digit(base)?;
        previous_underscore = false;
        value = value
            .saturating_mul(i128::from(base))
            .saturating_add(i128::from(digit))
            .min(1 << 100);
    }
    if previous_underscore {
        return None;
    }
    Some(if negative { -value } else { value })
}

/// `UnicodeDammit.numeric_character_reference`
fn numeric_character_reference(numeric: i128) -> String {
    const REPLACEMENT: &str = "\u{fffd}";
    if numeric <= 0 || numeric > 0x10ffff || (0xd800..=0xdfff).contains(&numeric) {
        return REPLACEMENT.into(); // 0, > 0x10FFFF, a surrogate, or a negative number (chr() raises ValueError)
    }
    let n = numeric as u32;
    // noncharacters resolve as they are; the windows-1252 replacement only applies to 0x80..=0x9f
    if (0x80..=0x9f).contains(&n) {
        if let Some(c) = tables().windows_1252.get(&n) {
            return c.to_string();
        }
    }
    char::from_u32(n).map_or_else(|| REPLACEMENT.into(), |c| c.to_string())
}

/// `BeautifulSoupHTMLParser._dereference_numeric_character_reference`: `(dereferenced, extra_data)`
fn dereference_numeric_character_reference(name: &str) -> (String, String) {
    let (name, base) = if name.starts_with(['x', 'X']) {
        (&name[1..], 16)
    } else {
        (name, 10)
    };
    if let Some(real) = py_int(name, base) {
        return (numeric_character_reference(real), String::new());
    }
    // _DECIMAL_/_HEX_REFERENCE_WITH_FOLLOWING_DATA: ^([0-9]+)(.*) / ^([0-9a-f]+)(.*)   ('.' does not match "\n")
    let digits = name
        .bytes()
        .take_while(|b| {
            if base == 16 {
                matches!(b, b'0'..=b'9' | b'a'..=b'f')
            } else {
                b.is_ascii_digit()
            }
        })
        .count();
    if digits == 0 {
        return (String::new(), name.to_string());
    }
    let extra = &name[digits..];
    let extra = &extra[..extra.find('\n').unwrap_or(extra.len())];
    let real = py_int(&name[..digits], base).unwrap_or(0);
    (numeric_character_reference(real), extra.to_string())
}

// ---------------------------------------------------------------------------------------------------------------------
// html.parser regular expressions as scanners (byte offsets; all sets are ASCII so multi-byte characters are never split)
// ---------------------------------------------------------------------------------------------------------------------

/// `[\t\n\r\f ]`
fn is_ws(b: u8) -> bool {
    matches!(b, b'\t' | b'\n' | b'\r' | 0x0c | b' ')
}

fn char_len(s: &str, p: usize) -> usize {
    s[p..].chars().next().map_or(1, char::len_utf8)
}

/// the `(?<=['"\t\n\r\f /])` of the attribute-name patterns
fn lookbehind_ok(b: &[u8], p: usize) -> bool {
    p > 0 && (matches!(b[p - 1], b'\'' | b'"' | b'/') || is_ws(b[p - 1]))
}

/// The optional value of an attribute: `[\t\n\r\f ]*=[\t\n\r\f ]*('[^']*'|"[^"]*"|(?!['"])[^>\t\n\r\f ]*)` at `p`, with the regex's
/// backtracking into the whitespace run. Returns the end, or `None` when the (optional) group does not match.
fn match_value(b: &[u8], p: usize) -> Option<usize> {
    let mut q = p;
    while q < b.len() && is_ws(b[q]) {
        q += 1;
    }
    if q >= b.len() || b[q] != b'=' {
        return None;
    }
    q += 1;
    let ws_start = q;
    while q < b.len() && is_ws(b[q]) {
        q += 1;
    }
    let mut pos = q;
    loop {
        match b.get(pos) {
            Some(&quote @ (b'\'' | b'"')) => {
                if let Some(close) = b[pos + 1..].iter().position(|&c| c == quote) {
                    return Some(pos + 1 + close + 1);
                }
            }
            _ => {
                let mut e = pos;
                while e < b.len() && b[e] != b'>' && !is_ws(b[e]) {
                    e += 1;
                }
                return Some(e);
            }
        }
        if pos == ws_start {
            return None;
        }
        pos -= 1; // give one whitespace character back
    }
}

/// `locatetagend.match(rawdata, start).end()` (`start` points at the tag name's first letter)
fn locatetagend(s: &str, start: usize) -> usize {
    let b = s.as_bytes();
    let n = b.len();
    let mut p = start + 1;
    while p < n && !(is_ws(b[p]) || b[p] == b'/' || b[p] == b'>') {
        p += 1;
    }
    while p < n && (is_ws(b[p]) || b[p] == b'/') {
        p += 1;
    }
    while p < n && lookbehind_ok(b, p) && !(is_ws(b[p]) || b[p] == b'/' || b[p] == b'>') {
        p += char_len(s, p);
        while p < n && !(is_ws(b[p]) || matches!(b[p], b'/' | b'=' | b'>')) {
            p += 1;
        }
        if let Some(e) = match_value(b, p) {
            p = e;
        }
        while p < n && (is_ws(b[p]) || b[p] == b'/') {
            p += 1;
        }
    }
    if p < n && b[p] == b'>' {
        p += 1;
    }
    p
}

/// `tagfind_tolerant.match(rawdata, p)`: `(group(1), end)`
fn tagfind_tolerant(s: &str, p: usize) -> (&str, usize) {
    let b = s.as_bytes();
    let n = b.len();
    let mut e = p + 1;
    while e < n && !(is_ws(b[e]) || b[e] == b'/' || b[e] == b'>') {
        e += 1;
    }
    let mut k = e;
    while k < n && (is_ws(b[k]) || (b[k] == b'/' && b.get(k + 1) != Some(&b'>'))) {
        k += 1;
    }
    (&s[p..e], k)
}

/// `attrfind_tolerant.match(rawdata, k).end()`
fn attrfind_tolerant(s: &str, k: usize) -> Option<usize> {
    let b = s.as_bytes();
    let n = b.len();
    if k >= n || !lookbehind_ok(b, k) || is_ws(b[k]) || b[k] == b'/' || b[k] == b'>' {
        return None;
    }
    let mut p = k + char_len(s, k);
    while p < n && !(is_ws(b[p]) || matches!(b[p], b'/' | b'=' | b'>')) {
        p += 1;
    }
    if let Some(e) = match_value(b, p) {
        p = e;
    }
    while p < n && (is_ws(b[p]) || (b[p] == b'/' && b.get(p + 1) != Some(&b'>'))) {
        p += 1;
    }
    Some(p)
}

/// `charref.match(rawdata, i)`: `(name, end_of_name, end_of_match)`; the match includes one terminating character.
fn match_charref(s: &str, i: usize) -> Option<(&str, usize, usize)> {
    let b = s.as_bytes();
    let mut p = i + 2;
    let start = p;
    if b.get(p).is_some_and(u8::is_ascii_digit) {
        while b.get(p).is_some_and(u8::is_ascii_digit) {
            p += 1;
        }
    } else if matches!(b.get(p), Some(b'x' | b'X'))
        && b.get(p + 1).is_some_and(u8::is_ascii_hexdigit)
    {
        p += 1;
        while b.get(p).is_some_and(u8::is_ascii_hexdigit) {
            p += 1;
        }
    } else {
        return None;
    }
    let term = s[p..].chars().next()?;
    if term.is_ascii_hexdigit() {
        return None;
    }
    Some((&s[start..p], p, p + term.len_utf8()))
}

/// `entityref.match(rawdata, i)`: `(name, end_of_name, end_of_match)`
fn match_entityref(s: &str, i: usize) -> Option<(&str, usize, usize)> {
    let b = s.as_bytes();
    let start = i + 1;
    if !b.get(start).is_some_and(u8::is_ascii_alphabetic) {
        return None;
    }
    let mut p = start + 1;
    while b
        .get(p)
        .is_some_and(|c| c.is_ascii_alphanumeric() || *c == b'-' || *c == b'.')
    {
        p += 1;
    }
    if let Some(term) = s[p..].chars().next() {
        return Some((&s[start..p], p, p + term.len_utf8()));
    }
    // at the end of the data the regex backtracks to the last '-' or '.' of the name
    let cut = (start + 1..p)
        .rev()
        .find(|&q| b[q] == b'-' || b[q] == b'.')?;
    Some((&s[start..cut], cut, cut + 1))
}

fn starttagopen(s: &str, i: usize) -> bool {
    s.as_bytes().get(i + 1).is_some_and(u8::is_ascii_alphabetic)
}

fn endtagopen(s: &str, i: usize) -> bool {
    s.as_bytes().get(i + 2).is_some_and(u8::is_ascii_alphabetic)
}

/// `rawdata[i:i+9].lower() == '<!doctype'`
fn is_doctype(s: &str, i: usize) -> bool {
    let head = &s[i..];
    head.len() >= 9 && head.is_char_boundary(9) && head[..9].eq_ignore_ascii_case("<!doctype")
}

